# Every row of code_weekly_stats with the ldap it counts towards. Gerrit rows
# already carry the ldap. A GitHub row goes through users.github_user_id to the
# person's confirmed company address; with no such person its ldap is NULL.
# min() keeps one row per stats row if a person ever holds two company
# addresses, matching ldap_from_addresses, which reads the first one sorted.
CREATE_BY_LDAP_VIEW = """
CREATE VIEW code_weekly_stats_by_ldap AS
SELECT s.source, s.account, s.repo, s.week_start,
       s.merged, s.loc_merged, s.reviewed, s.closed,
       CASE WHEN s.source = 'gerrit' THEN s.account ELSE gh.ldap END AS ldap
FROM code_weekly_stats s
LEFT JOIN LATERAL (
    SELECT split_part(min(ue.email), '@', 1) AS ldap
    FROM users u
    JOIN user_emails ue
      ON ue.user_id = u.user_id
     AND ue.otp_confirmed
     AND lower(ue.email) LIKE '%@circlecat.org'
    WHERE s.source = 'github'
      AND u.github_user_id::text = s.account
) gh ON true
"""


